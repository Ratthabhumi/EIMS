"""Generate the Independent Human Review package from the live catalogs (no hand-typed content).

Every entry is PENDING_HUMAN_REVIEW. Reviewer fields are intentionally blank: AI agents must never fill in a reviewer
identity, decision or validation status.  Usage: python tools/build_human_review_package.py [output.md]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.domain.analyzer.services.vendor_diagnostics import DIAGNOSTIC_CANDIDATES, STATE_KINDS  # noqa: E402
from backend.domain.analyzer.services.operational_catalog import OPERATIONAL_CATALOG  # noqa: E402

DEFAULT_OUT = ROOT / "docs/acceptance/2026-11-20-human-review-package.md"
DISP = json.loads((ROOT / "backend/domain/analyzer/services/windows_reference_dispositions.json").read_text(encoding="utf-8"))["records"]
CAT = {(e["event_id"], e["provider"]): e for e in OPERATIONAL_CATALOG if e["source_family"] == "windows_event"}
BLANK = ("| Reviewer name | Review date | Decision (ACCEPT / ACCEPT_WITH_CHANGES / REJECT / NEEDS_MORE_EVIDENCE) | Notes |\n|---|---|---|---|\n|  |  |  |  |\n")


def bullets(items):
    return "\n".join(f"- {x}" for x in items) if items else "- (none recorded)"


def candidate_block(c):
    kind = c.get("detection_kind", "log_or_symptom")
    srcs = "\n".join(f"- [{s['title']}]({s['url']}) — scope: {s['scope']} (retrieved {s.get('retrieved', '?')}, page date {s.get('page_date', 'n/a')})" for s in c["official_sources"])
    cmds = "\n".join(f"- `{d['command']}` → expected evidence: {d['expected_evidence']}" for d in c["diagnostic_commands"])
    link = {k: c[k] for k in ("sqlstate_codes", "documented_messages", "field_conditions", "evaluator") if c.get(k)}
    out = [f"### {c['candidate_id']}", f"*{c['vendor']} — {c['product']} — detection kind: **{kind}** — mapping: `{c['parser_mapping']}` — review_status: **{c['review_status']}***", "",
           f"**Version scope:** {c['version_scope']}", "", f"**Candidate definition (symptom):** {c['symptom']}", "", f"**Explanation (meaning):** {c['meaning']}", "",
           "**Signatures / detection logic:**", bullets(c.get("signatures", [])), ""]
    if link:
        out += ["**Parser/evaluator linkage:** `" + json.dumps(link, ensure_ascii=False) + "`", ""]
    if c.get("detection_signals"):
        out += ["**Detection signals (state/telemetry):**", bullets(c["detection_signals"]), ""]
    out += ["**Documented thresholds:** " + (json.dumps(c["documented_thresholds"], ensure_ascii=False) if c.get("documented_thresholds") else "none documented — none applied"), "",
            "**Expected evidence (commands):**", cmds, "", "**Likely causes (as sourced):**", bullets(c["likely_causes"]), "",
            "**False-positive risks:**", bullets(c.get("false_positive_risks", [])), "",
            "**Validation / fixture method:** " + (c.get("validation_method") or "log-line fixtures in tests/test_vendor_diagnostic_candidates.py"), "",
            "**Uncertainties / limitations:** " + c["limitations"], "", "**Evidence basis:** " + c["evidence_basis"], "", "**Sources:**", srcs, "",
            "**Review questions:**",
            "1. Does each cited page, read in full by a human, state what the explanation attributes to it, for the stated version scope?",
            "2. Is anything stated more strongly than the source supports (cause, threshold, version applicability)?",
            "3. Could the detection logic match an unrelated event (false positive) or miss a documented variant?",
            "4. Are the commands and expected evidence safe to show an operator?", "", BLANK]
    return "\n".join(out)


def disposition_block(r):
    rec = CAT[(r["event_id"], r["provider"])]
    refs = "\n".join(f"- [{x['title']}]({x['url']}) — {x.get('scope', '')}" for x in r["references"]) or "- (no reference)"
    return "\n".join([f"### Windows {r['provider']} {r['event_id']} — {r['disposition']}", f"*Catalog title: {rec['title']} — review_status: **{r['review_status']}***", "",
                      f"**Catalog description:** {rec['description']}", "", f"**Note:** {r['note']}", "", "**References:**", refs, "",
                      f"**Search metadata:** {json.dumps(r.get('search', r.get('candidate_pages_checked', '')), ensure_ascii=False)}", "",
                      "**Review questions:** (1) Does a human reading the page confirm the Event ID and meaning? (2) Is the scope (general vs one scenario) stated correctly? (3) For NO_AUTHORITATIVE_REFERENCE_FOUND/NEEDS_HUMAN_REVIEW: is there a Microsoft page the search missed?", "", BLANK])


def main(out: Path):
    new_or_state = [c for c in DIAGNOSTIC_CANDIDATES]
    parts = ["# Independent Human Review Package — EIMS Knowledge Foundation (2026-11-20)", "",
             "Generated by `tools/build_human_review_package.py` from the live catalogs. **Every entry is PENDING_HUMAN_REVIEW.** "
             "Reviewer fields are blank on purpose: no reviewer identity, decision or approval has been recorded by any AI agent, and nothing here "
             "is promoted beyond `candidate`.", "",
             f"Entries: {len(DISP)} Windows dispositions, {len(new_or_state)} diagnostic candidates "
             f"({sum(c.get('detection_kind') in STATE_KINDS for c in new_or_state)} state/telemetry). The 28 legacy parser-linked catalog candidates and the 658 reference records are "
             "unchanged by this tranche and are not repeated here.", "", "## Part A — Windows reference dispositions (54 records that lacked an exact reference)", ""]
    parts += [disposition_block(r) for r in DISP]
    parts += ["", "## Part B — Diagnostic candidates (log-parser-linked, field-linked and state/telemetry)", ""]
    parts += [candidate_block(c) for c in sorted(new_or_state, key=lambda x: (x["vendor"], x["candidate_id"]))]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(DISP)} dispositions, {len(new_or_state)} candidates)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT)
