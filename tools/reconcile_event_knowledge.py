"""Generate the 39-record reconciliation matrix for event_knowledge.json against the canonical catalog.

Usage: PYTHONPATH=. python tools/reconcile_event_knowledge.py docs/knowledge/EVENT_KNOWLEDGE_RECONCILIATION_20261120.md
"""
import json
import sys
from pathlib import Path

from backend.domain.analyzer.services.operational_catalog import resolve_windows_entry

ROOT = Path("backend/domain/analyzer/services")
CUR = json.loads((ROOT / "event_knowledge.json").read_text(encoding="utf-8"))
BASE = set(json.loads(Path("tests/data/knowledge_baseline_ids_20261119.json").read_text(encoding="utf-8"))["ids"])
CORRECTED = {"5011": "curated text described event 5010 ('hung / failed to ping WAS'); corrected",
             "109": "curated text said 'shutdown transition'; sources say power-state transition; corrected"}
CONFLICT_NOTE = {"5011": "plain ID 5011 is Windows Defender in the 163 baseline: different provider, same ID",
                 "1001": "plain ID 1001 is Windows Error Reporting in the baseline: different provider, same ID"}
NO_SOURCE = "none verified"
OFFICIAL = {"1135": "Microsoft KB 3036113 + Learn failover-cluster system events", "1511": "Learn TechNet-wiki archive page",
            "1530": "Microsoft KB 947238", "5011": "Learn IIS process-crash guidance (5011 only)",
            "17": "Learn WHEA page (provider name only)", "1026": "n/a"}


def main(out):
    rows = []
    for eid, body in CUR.items():
        en = body["en"]
        provs = body.get("provider_names", [])
        if not provs:
            rows.append((eid, "-", "-", "n/a", "not a Windows event (Hitachi JP1 message ID)",
                         f"{len(en.get('causes', []))} causes / {len(en.get('steps', []))} steps", NO_SOURCE,
                         "DEFERRED: needs a vendor family + Hitachi source; stays in the second store"))
            continue
        found = resolve_windows_entry(eid, provs[0])
        rec = found["entry"]
        cid = rec["catalog_id"] if rec else "-"
        existed = "baseline" if cid in BASE else "NEW (migrated)"
        carried = bool(rec and rec.get("diagnostic_guidance", {}).get("localized_summary"))
        if eid in CORRECTED:
            content = "CORRECTED then migrated: " + CORRECTED[eid]
        elif cid in BASE:
            content = "topic duplicated by baseline record; causes/steps were UNIQUE -> carried verbatim"
        else:
            content = "no baseline record -> migrated verbatim as new record"
        if eid in CONFLICT_NOTE:
            content += "; " + CONFLICT_NOTE[eid]
        rows.append((eid, "; ".join(provs), cid, existed, content,
                     f"{len(en.get('causes', []))} causes / {len(en.get('steps', []))} steps",
                     OFFICIAL.get(eid, NO_SOURCE),
                     "migrated" if carried else "MISSING"))
    lines = ["# event_knowledge.json reconciliation (2026-11-20)", "",
             f"Records: {len(rows)}. Generated by `tools/reconcile_event_knowledge.py`; parity enforced by `tests/test_event_knowledge_parity.py`.", "",
             "| Event ID | Provider(s) | Canonical record | Origin | Duplicated / unique content | Unique diagnostic info (en) | Authoritative source | Action |",
             "|---|---|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(rows), "rows;", sum(1 for r in rows if r[-1] == "migrated"), "migrated;",
          sum(1 for r in rows if r[-1].startswith("DEFERRED")), "deferred;", sum(1 for r in rows if r[-1] == "MISSING"), "missing")


if __name__ == "__main__":
    main(sys.argv[1])
