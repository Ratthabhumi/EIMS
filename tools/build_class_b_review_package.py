"""Generate the Class B (parser-linked diagnostic candidates) human review package from the live register, catalogs and
run-bound evidence. Reviewer fields are blank on purpose: no reviewer, decision or date is ever written by this tool.

Output: docs/acceptance/certification/class_b_human_review_package.md (+ .json)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
SERVICES = ROOT / "backend" / "domain" / "analyzer" / "services"
CERT = ROOT / "docs" / "acceptance" / "certification"
BLANK = ("| Reviewer (authenticated human) | Role / authority | Review date | Decision | Notes |\n|---|---|---|---|---|\n|  |  |  |  |  |\n")


def _load():
    reg = {r["record_key"]: r for r in json.loads((CERT / "register.json").read_text(encoding="utf-8"))["records"]}
    legacy = {f"diagnostic_legacy:{e['source_family']}:{e['code_type']}:{e['diagnostic_code']}": e
              for e in json.loads((SERVICES / "diagnostic_knowledge_catalog.json").read_text(encoding="utf-8"))["entries"]}
    cands = {f"candidate:{r['candidate_id']}": r for r in json.loads((SERVICES / "vendor_diagnostic_catalog.json").read_text(encoding="utf-8"))["records"]}
    cases: dict[str, list[dict]] = {}
    for c in json.loads((CERT / "technical_evidence_matching.json").read_text(encoding="utf-8"))["cases"]:
        cases.setdefault(c["record_key"], []).append(c)
    return reg, legacy, cands, cases


def _bul(items, empty="(none recorded)"):
    items = [str(i) for i in items if str(i).strip()]
    return "\n".join(f"- {i}" for i in items) if items else f"- {empty}"


def _facts(key, rec, legacy, cands):
    if key in legacy:
        e = legacy[key]
        g = e.get("diagnostic_guidance") or {}
        return {"kind": "legacy", "title": e["title"], "meaning": e["description"], "version": e.get("compatibility_scope", ""),
                "sources": [f"[{r.get('title', r['url'])}]({r['url']}) — {r.get('scope', '')}" for r in e.get("official_references", [])],
                "signatures": e.get("observed_signatures", []), "investigation": e.get("investigation_steps", []), "commands": [],
                "causes": [], "alt": [], "fp": [], "limitations": e.get("limitations", ""), "maturity": e.get("support_level", ""),
                "remediation": g.get("safe_remediation") or [], "risk": g.get("risk") or "", "rollback": g.get("rollback") or "",
                "recovery": g.get("verification_criteria") or [], "legacy_label": e.get("verification_status", "")}
    r = cands[key]
    return {"kind": "candidate", "title": r["candidate_id"], "meaning": r["meaning"], "version": r["version_scope"],
            "sources": [f"[{s['title']}]({s['url']}) — {s['scope']} (retrieved {s.get('retrieved', '?')})" for s in r["official_sources"]],
            "signatures": r.get("signatures", []), "investigation": r.get("diagnostic_steps", []),
            "commands": [f"`{c['command']}` → {c['expected_evidence']}" for c in r.get("diagnostic_commands", [])],
            "causes": r.get("likely_causes", []), "alt": r.get("alternative_causes", []), "fp": r.get("false_positive_risks", []),
            "limitations": r.get("limitations", ""), "maturity": r.get("evidence_maturity", ""), "remediation": r.get("remediation", []),
            "risk": r.get("operational_risk", ""), "rollback": "", "recovery": r.get("verification_steps", []), "legacy_label": ""}


def build() -> tuple[str, list[dict]]:
    reg, legacy, cands, cases = _load()
    rows = sorted((r for r in reg.values() if r["cert_class"] == "B"), key=lambda r: r["record_key"])
    out = ["# Class B Human Review Package — parser-linked diagnostic candidates", "",
           "Generated by `tools/build_class_b_review_package.py` from the register, catalogs and run-bound evidence. **No reviewer, decision, date or approval "
           "has been written by any AI or tool.** Every record is `SOURCE_UNVERIFIED`, `INDEPENDENT_REVIEW_PENDING`, `NOT_APPROVED`. Evidence rows show the "
           "recorded expected and actual results of synthetic fixtures run through the real parser/Analyzer path; they are not customer logs.", "",
           f"Records: {len(rows)}. Review a record only if its content hash below equals the register's current hash; otherwise the evidence is stale.", "",
           "## Reviewer governance (what must exist before a decision can be recorded)",
           "A decision must be written by an **authenticated human** with a recorded role/authority, tied to the record content hash, with evidence references, a "
           "rationale and a timestamp; re-reviews supersede, never overwrite. The current governance tables cover only the 181 loaded legacy/Windows records and "
           "do not yet distinguish human from AI/automation actors (see `knowledge_model_gap_analysis.md`). **Blocker: until that is implemented, decisions "
           "recorded in this document are notes, not governance records.**", ""]
    index = []
    for row in rows:
        key = row["record_key"]
        f = _facts(key, row, legacy, cands)
        ev = cases.get(key, [])
        pos = [c for c in ev if c["polarity"] == "positive"]
        neg = [c for c in ev if c["polarity"] == "negative"]
        ready = row["readiness"]
        missing = [n for n, v in (("remediation", f["remediation"]), ("risk statement", f["risk"]), ("rollback", f["rollback"] or (f["kind"] == "candidate" and "")),
                                  ("recovery verification", f["recovery"])) if not (v and str(v).strip() and not str(v).lower().startswith("not stated"))]
        index.append({"record_key": key, "content_hash": row["content_hash"], "missing_operational_fields": missing})
        out += [f"## {key}", "", f"*Content hash:* `{row['content_hash'][:16]}…` — *Gate:* source `{ready['source']}`, technical `{ready['technical']}`, "
                f"review `{ready['independent_review']}`, approval `{ready['approval']}`; source blockers: {ready['source_blockers'] or 'none'}; "
                f"technical blockers: {ready['blockers'] or 'none'}", ""]
        if f["legacy_label"]:
            out += [f"*Legacy label:* `{f['legacy_label']}` — a legacy catalog label with **no recorded human reviewer**; it is not source verification.", ""]
        out += ["**1-2. Diagnostic meaning**", "", f"{f['title']}: {f['meaning']}", "", "**3. Source and version scope**", "", _bul(f["sources"]),
                "", f"Version scope: {f['version'] or '(not stated)'}", "",
                "**4. Parser / evaluator path**", "", f"`{(row['parser_or_evaluator'] or {}).get('mapping', '')}` `{(row['parser_or_evaluator'] or {}).get('symbol', '')}` — "
                "`parse_event_metadata` → catalog resolution → Analyzer summary (as exercised by the evidence below).", "",
                "**Signatures / signals:**", _bul(f["signatures"]), "",
                "**5. Positive evidence** (input → expected → actual)", ""]
        out += [f"- `{c['input_preview'][:110]}` → expected `{json.dumps(c['expected'])}` → actual `{json.dumps(c['actual'])}` — {'PASS' if c['passed'] else 'FAIL'}" for c in pos] or ["- none"]
        out += ["", "**6. Negative evidence**", ""]
        out += [f"- {c['why']}: `{c['input_preview'][:90]}` → {c['expected']} → actual `{json.dumps(c['actual'])}` — {'PASS' if c['passed'] else 'FAIL'}" for c in neg] or ["- none"]
        out += ["", "**7-8. Expected vs actual:** all recorded cases " + ("passed" if ev and all(c["passed"] for c in ev) else "have NOT all passed") +
                f" ({len(pos)} positive, {len(neg)} negative; evidence file `technical_evidence_matching.json`).", "",
                "**9. False positive / false negative considerations**", _bul(f["fp"] or ["No record-level false-positive list; the negative cases above are the only recorded ones."]), "",
                "Alternative causes:", _bul(f["alt"]), "",
                "**10. Confidence and limitations**", "", f"Maturity: `{f['maturity']}`. {f['limitations']}", "",
                "**11. Remediation and risk**", "", "Remediation:", _bul(f["remediation"], "(none recorded)"), "", f"Risk: {f['risk'] or '(not recorded)'}", "",
                f"Rollback: {f['rollback'] or '(not recorded as a separate field)'}", "",
                "**12. Evidence required to verify recovery**", "", _bul(f["recovery"], "NOT RECORDED — reviewer must decide what proves recovery"), "",
                "**Investigation:**", _bul(f["investigation"] + f["commands"]), "",
                "**13. Reviewer questions**",
                "1. Does the cited page, read in full, support the meaning and version scope above? Quote the passage.",
                "2. Could the signature match an unrelated event (false positive) or miss a documented variant (false negative)?",
                "3. Is each remediation step safe to show to an operator, with its risk and rollback?" + (" (Missing fields: " + ", ".join(missing) + ")" if missing else ""),
                "4. What observable evidence proves the problem is resolved, and when must an engineer escalate?", "",
                "**14. Reviewer decision (blank — human only)**", "", BLANK]
    return "\n".join(out) + "\n", index


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=CERT / "class_b_human_review_package.md")
    args = parser.parse_args(argv)
    text, index = build()
    args.output.write_text(text, encoding="utf-8")
    args.output.with_suffix(".json").write_text(json.dumps({"schema_version": 1, "records": index}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"records": len(index), "with_missing_operational_fields": sum(bool(r["missing_operational_fields"]) for r in index)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
