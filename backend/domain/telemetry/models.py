import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import (
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from backend.infrastructure.database import Base


def _utcnow() -> datetime:
    return datetime.now(UTC)


class TelemetryMetric(Base):
    """
    Time-series repository entity storing computational runtime health metrics
    emitted continuously by remote Discovery Agents (Core Law 4 Section 6.2).
    """
    __tablename__ = "telemetry_metrics"

    metric_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        doc="Universally unique metric record identifier."
    )
    asset_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("infrastructure_assets.asset_id", ondelete="CASCADE"),
        nullable=False,
        doc="Foreign key reference binding metrics to origin compute asset."
    )
    event_time: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        doc="Timestamp of physical metric sampling occurrence (UTC)."
    )
    cpu_utilization: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Recorded CPU utilization percentage (0.0 to 100.0)."
    )
    source_event_key: Mapped[str | None] = mapped_column(String(160), nullable=True)
    diagnostic_payload: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
        doc="Extensible JSON attribute dictionary capturing RAM, IOPS, and network bandwidth."
    )

    __table_args__ = (
        Index("idx_telemetry_asset_time", "asset_id", "event_time"),
        Index("uq_telemetry_metrics_source_event_key", "source_event_key", unique=True),
        {"comment": "High-frequency operational metrics governed under Core Law 4."}
    )


class WindowsEventLog(Base):
    """
    Stores structural Windows Operating System diagnostic and security events captured
    during continuous log inspection. Features polymorphic GIN Indexing.
    """
    __tablename__ = "windows_event_logs"

    log_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        doc="Unique log event processing record ID."
    )
    asset_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("infrastructure_assets.asset_id", ondelete="CASCADE"),
        nullable=False,
        doc="Host asset that generated the native .evtx stream event."
    )
    occurrence_time: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        doc="Precise timestamp generated by origin operating system eventing."
    )
    event_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        doc="Canonical Windows Event Log numeric identifier (e.g., 4624, 4625)."
    )
    severity_level: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
        doc="Categorized runtime criticality (Information, Warning, Critical)."
    )
    source_event_key: Mapped[str | None] = mapped_column(String(160), nullable=True)
    evtx_metadata: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
        doc="Deserialized event properties and extensible forensic diagnostic parameters."
    )

    __table_args__ = (
        Index("idx_winlog_metadata_gin", "evtx_metadata", postgresql_using="gin"),
        Index("uq_windows_event_logs_source_event_key", "source_event_key", unique=True),
        # Brute-force (4625) per-source-IP window count; must match migration a3d6f1e8c295.
        Index("idx_winlog_4625_src_ip_time",
              text("(evtx_metadata ->> 'source_network_ip')"), "occurrence_time",
              postgresql_where=text("event_id = 4625")),
        {"comment": "Windows diagnostic logs featuring polymorphic GIN-indexed metadata."}
    )


class TelemetryAlertOutbox(Base):
    """Transactional outbox: written in the same transaction as the quarantine/AuditLog.

    A dispatcher publishes pending rows (published_at IS NULL) to a durable Redis Stream
    after commit and stamps published_at only once XADD is confirmed (at-least-once;
    consumers dedupe on alert_id).
    """
    __tablename__ = "telemetry_alert_outbox"

    alert_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4,
        doc="Stable alert identifier, also emitted in the published payload for consumer dedupe.")
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=_utcnow)
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    __table_args__ = (
        Index("idx_telemetry_alert_outbox_pending", "created_at",
              postgresql_where=text("published_at IS NULL")),
    )
